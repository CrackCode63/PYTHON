# Introduction to OOPs
# What is OOPs?
# OOPs stands for Object-Oriented Programming. It is a programming paradigm that revolves around the concept of objects and classes. In OOPs, we define a class that represents a real-world entity, and then create objects from that class. Each object has its own set of attributes (data) and methods (functions) that can be used to interact with it.

# What is class in OOPs
# A class is a blueprint or a template that defines the properties and behavior of an object. It is essentially a design pattern or a template that defines the characteristics of an object. A class can have attributes (data) and methods (functions) that can be used to interact with it.

# What is object in OOPs
# An object is an instance of a class. It has its own set of attributes (data) and methods (functions) that can be used to interact with it. Objects are the actual entities that we work with in a program.

