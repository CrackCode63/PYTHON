# what is lambda funtion?
# In Python, a lambda function (also known as an anonymous function) is a small, single-line function that can be defined inline within a larger expression. It's a shorthand way to create a function without declaring a separate named function using the def keyword.

# The syntax for a lambda function is:
# lambda arguments: expression
# where arguments is a comma-separated list of variables that will be passed to the function, and expression is the code that will be executed when the function is called.


double = lambda x: x * 2
print(double(5))  # Output: 10